def plot_sq_logit_diff_comparison(method_results, bin_centers, out_path):
    fig, axes = plt.subplots(
        1,
        len(method_results),
        figsize=(11, 3),
        sharey=False,
    )

    if len(method_results) == 1:
        axes = [axes]

    method_official_names = {
        "GA": "Gradient Ascent",
        "RL": "Random Labels",
    }

    for ax, (method_name, (cfg, stats_full, setting_full)) in zip(
        axes, method_results.items()
    ):

        _plot_sq_logit_diff_on_ax(ax, cfg, bin_centers, stats_full, setting_full)
        ax.set_title(
            f"{method_official_names[method_name]} + {cfg.model_type} regression"
        )
        ax.legend(fontsize=12)

    fig.tight_layout()
    fig.savefig(out_path)
    plt.close(fig)


def _plot_flip_rate_on_ax(ax, cfg, bin_centers, stats_full):

    official_method_names = {
        "ga": "Gradient Ascent",
        "rl": "Random Labels",
    }
    for confidence_level, stats in stats_full.items():
        mean = stats["flip_rate"]["mean"]
        stderr = stats["flip_rate"]["stderr"]

        label_addition = (
            f", deleted prob is {confidence_level}" if confidence_level else ""
        )

        ax.plot(
            bin_centers,
            mean,
            label=f"{official_method_names[cfg.unlearning_method]}{label_addition}",
        )
        ax.fill_between(
            bin_centers,
            mean - stderr,
            mean + stderr,
            alpha=0.25,
        )

        if "full_flip_rate" in stats:
            full_mean = stats["full_flip_rate"]["mean"]
            full_stderr = stats["full_flip_rate"]["stderr"]
            ax.plot(
                bin_centers,
                full_mean,
                label=f"Before unlearning{label_addition}",
            )
            ax.fill_between(
                bin_centers,
                full_mean - full_stderr,
                full_mean + full_stderr,
                alpha=0.2,
            )

    ax.set_xlabel(r"$\dfrac{\langle x_q, x_f \rangle}{\|x_f\|^2}$")
    ax.set_ylabel("Flip probability")
    ax.set_title("Label flip rate by ripple interval")
    ax.grid(alpha=0.3)


def _plot_logit_variance_on_ax(ax, cfg, bin_centers, stats_full):
    for confidence_level, stats in stats_full.items():
        label_addition = (
            f", deleted prob is {confidence_level}" if confidence_level else ""
        )

        mean = stats["delta_logit_var"]["mean"]
        stderr = stats["delta_logit_var"]["stderr"]

        plt.plot(
            bin_centers,
            mean,
            label=rf"Var(logit shift){label_addition}",
        )
        plt.fill_between(
            bin_centers,
            mean - stderr,
            mean + stderr,
            alpha=0.25,
        )
    ax.set_xlabel(r"$\dfrac{\langle x_q, x_f \rangle}{\|x_f\|^2}$")
    ax.set_ylabel(r"$\mathrm{Var}(\Delta \mathrm{logit})$")
    ax.set_title("Variance of logit shift by ripple interval")
    ax.grid(alpha=0.3)


