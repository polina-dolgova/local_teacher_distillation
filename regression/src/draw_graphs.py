def fit_pure_quadratic(
    x: np.ndarray,
    y: np.ndarray,
    weights: np.ndarray | None = None,
) -> float:
    """
    Fit y ≈ a * x^2 by weighted least squares.
    """
    mask = np.isfinite(x) & np.isfinite(y) & (x <= 0.60) & (x >= -0.60)
    x = x[mask]
    y = y[mask]

    z = x**2

    if weights is None:
        denom = np.sum(z**2)
        if denom <= 1e-15:
            return float("nan")
        a = np.sum(z * y) / denom
    else:
        w = weights[mask]
        denom = np.sum(w * z**2)
        if denom <= 1e-15:
            return float("nan")
        a = np.sum(w * z * y) / denom

    return float(a)


