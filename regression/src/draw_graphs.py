def plot_rl_flip_and_variance_fixed_xa(
    cfg,
    bin_centers,
    stats_full,
    out_path,
):
    fig, axes = plt.subplots(
        1,
        2,
        figsize=(13, 5),
        sharex=True,
        sharey=False,
    )

    ax_var, ax_flip = axes

    label_map = {
        "low": r"low x_f conf $\in [0.50, 0.65]$",
        "mid": r"mid x_f conf $\in [0.65, 0.80]$",
        "high": r"high x_f conf $\in [0.80, 1.0]$",
        None: r"all deleted points",
    }

    for confidence_level, stats in stats_full.items():
        label = label_map[confidence_level]

        var_mean = stats["delta_logit_var_fixed_xa"]["mean"]
        var_stderr = stats["delta_logit_var_fixed_xa"]["stderr"]

        ax_var.plot(bin_centers, var_mean, label=label)
        ax_var.fill_between(
            bin_centers,
            var_mean - var_stderr,
            var_mean + var_stderr,
            alpha=0.25,
        )

        flip_mean = stats["flip_prob_fixed_xa"]["mean"]
        flip_stderr = stats["flip_prob_fixed_xa"]["stderr"]

        ax_flip.plot(bin_centers, flip_mean, label=label)
        ax_flip.fill_between(
            bin_centers,
            flip_mean - flip_stderr,
            flip_mean + flip_stderr,
            alpha=0.25,
        )

    ax_var.set_xlabel(r"$\dfrac{\langle x, x_f \rangle}{\|x_f\|^2}$")
    ax_var.set_ylabel(r"Mean $\mathrm{Var}(\Delta \mathrm{logit})$")
    ax_var.set_title(r"Variance of $\Delta \mathrm{logit}$")
    ax_var.grid(alpha=0.3)
    ax_var.legend()

    ax_flip.set_xlabel(r"$\dfrac{\langle x, x_f \rangle}{\|x_f\|^2}$")
    ax_flip.set_ylabel("Probability of disagreement with retrain")
    ax_flip.set_title("Prediction disagreement with retrain")
    ax_flip.grid(alpha=0.3)
    ax_flip.legend()

    fig.tight_layout()
    fig.savefig(out_path)
    plt.close(fig)
